export const workflowModuleIds = new Set([
  "admissions",
  "automation",
  "payments",
  "reports",
  "learning",
  "settings",
  "analytics",
  "security",
]);

export function getModuleStatus(id: string): ModuleStatus {
  if (productionModuleIds.has(id)) return "Active";
  if (workflowModuleIds.has(id)) return "Configured";
  return "Setup";
}

export function enrichModule(module: AdminModule): AdminModule {
  return {
    ...module,
    actions: module.actions ??
      moduleActions[module.id] ?? ["Create", "Assign", "Export", "Audit"],
    icon: module.icon ?? moduleIcons[module.id] ?? "dashboard",
    status: module.status ?? getModuleStatus(module.id),
  };
}

export const allModules = [...modules, ...extraModules].map(enrichModule);

export const moduleMap = Object.fromEntries(
  allModules.map((module) => [module.id, module]),
);

export function getModuleHref(id: string) {
  return id === "dashboard" ? "/" : `/${id}`;
}

export function resolveRouteModuleId(
  pathname: string | null,
  fallback: string,
) {
  const segment = pathname?.split("/").filter(Boolean)[0] ?? "";
  if (!segment) return "dashboard";
  if (segment === "organizations") return "organizations";
  if (moduleMap[segment]) return segment;
  if (fallback === "organizations") return "organizations";
  return moduleMap[fallback] ? fallback : "dashboard";
}
