const recurringStoreProducts = (tier: string, cycle: string) => ({
  android: {
    productId: `mentora_${tier}`,
    basePlanId: cycle,
    offerId: 'trial-7-days',
    productType: StoreProductType.SUBSCRIPTION,
  },
  ios: {
    productId: `mentora_${tier}_${cycle.replace('-', '_')}`,
    subscriptionGroupId: 'mentora_membership',
    productType: StoreProductType.SUBSCRIPTION,
  },
});

const selfServicePlan = (
  name: string,
  slug: string,
  tier: PlanTier,
  billingCycle: BillingCycle,
  price: number,
  durationDays: number,
  sortOrder: number,
  description: string,
  isPopular = false,
): Plan => ({
  name,
  slug,
  tier,
  planType: PlanType.SELF_SERVICE,
  billingCycle,
  price,
  durationDays,
  trialDays: tier === PlanTier.FREE ? 0 : 7,
  autoRenewDefault: true,
  isCustom: false,
  audience: 'consumer',
  enabledModules: [],
  userLimit: 1,
  branchLimit: 0,
  leadLimit: 0,
  storageLimitGb: 1,
  aiCreditLimit: tier === PlanTier.FREE ? 100 : 1000,
  currency: 'INR',
  isPopular,
  sortOrder,
  description,
  isActive: true,
  version: 1,
  storeProducts:
    tier === PlanTier.FREE
      ? undefined
      : recurringStoreProducts(tier.toLowerCase(), billingCycle),
});

